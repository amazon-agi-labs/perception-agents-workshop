function extractKeyTakeaways(fullSummary) {
  if (!fullSummary) return [];
  const match = fullSummary.match(/## Key Take\s*aways\s*\n([\s\S]*?)(?:\n## |$)/i);
  if (!match) return [];
  return match[1].split('\n')
    .map(line => line.replace(/^[-*]\s*/, '').replace(/\*\*/g, '').trim())
    .filter(line => line.length > 0);
}

function handleBeeEvent(event) {
  beeStreamStatus = 'connected';

  if (!event.conversation) return;

  const conv = event.conversation;
  const state = (conv.state || '').toLowerCase();
  const id = conv.id || conv.uuid;

  if (!id) return;

  if (state !== 'processed' && state !== 'completed') return;

  const title = conv.title || '';
  const shortSummary = conv.short_summary || '';

  process.stderr.write('[bee-conv] Completed conversation: "' + (title || shortSummary).substring(0, 60) + '" — fetching details...\n');

  fetchConversationDetails(id, function(details) {
    const fullSummary = (details && details.summary) || '';
    const combinedText = title + ' ' + shortSummary + ' ' + fullSummary;

    if (!isDesignRelated(combinedText)) {
      process.stderr.write('[bee-conv] Skipped non-design conversation: "' + (title || shortSummary).substring(0, 60) + '"\n');
      return;
    }

    const keyTakeaways = extractKeyTakeaways(fullSummary);
    const resolvedTitle = title || (details && details.title) || (details && details.short_summary) || shortSummary;

    const conversation = {
      id: String(id),
      uuid: conv.uuid || '',
      title: resolvedTitle,
      shortSummary: (details && details.short_summary) || shortSummary,
      fullSummary: fullSummary,
      keyTakeaways: keyTakeaways,
      state: state,
      details: details,
      transcript: null,
      timestamp: Date.now(),
      applied: false,
    };

    fetchConversationTranscript(id, function(transcript) {
      conversation.transcript = transcript;
      addConversation(conversation);
      process.stderr.write('[bee-conv] Added conversation: "' + resolvedTitle.substring(0, 60) + '" with ' + keyTakeaways.length + ' takeaways\n');
    });
  });
}

